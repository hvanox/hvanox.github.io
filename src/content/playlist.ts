/**
 * Плейлист плеера — ТОЛЬКО песни Kasane Teto.
 *
 * Откуда брать треки: piapro.jp (площадка Crypton). Условия, которые нас
 * устраивают: лицензия «некоммерческое использование + указание автора».
 * Портфолио некоммерческое, автор подписан в плеере + ссылка на страницу
 * трека — условия соблюдены. Прямую ссылку на mp3 даёт HTML страницы трека:
 *
 *   curl -s -A "Mozilla/5.0" "https://piapro.jp/t/XXXX" \
 *     | grep -o 'https://cdn.piapro.jp/[^"]*\.mp3'
 *
 * Бери ссылку с суффиксом _audition.mp3 (публичное превью, hotlink работает,
 * проверено: 200 + audio/mpeg + ranges). Полные файлы на 9+ МБ могут
 * требовать логин — их не трогаем.
 *
 * Стримы играют напрямую, без WebAudio-анализатора: чужой CDN не отдаёт
 * CORS-заголовки, а без них граф глушит звук. Канвас в этом случае
 * показывает статичную полосу — так задумано.
 */

export type Track = {
  id: string;
  title: string;
  artist: string;
  /** Прямой mp3 (свой /audio/... или чужой https) — играет <audio> напрямую. */
  src: string;
  /** Страница трека: ссылка-подпись автора (требование лицензии piapro). */
  sourceUrl: string;
  /** Строки текста песни для бегущей строки. Пусто — покажем название. */
  lyrics: string[];
  /** Зациклить (для коротких лупов). */
  loop?: boolean;
};

